//go:build ignore

// Command gencreds writes OAuth credentials from the environment into
// internal/oauth2/credentials_gen.go so builds do not pass them on the command
// line, where Wails and Go print them. The file is gitignored and compiled only
// with the mailven_creds build tag. Without credentials, the file is removed.
//
// Usage (from the repository root): go run build/gencreds.go
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
)

const outputPath = "internal/oauth2/credentials_gen.go"

// credentials maps environment variables to mailven-creds shim JSON keys.
var credentials = []struct{ env, key string }{
	{"GOOGLE_CLIENT_ID", "google_client_id"},
	{"GOOGLE_CLIENT_SECRET", "google_client_secret"},
	{"MICROSOFT_CLIENT_ID", "microsoft_client_id"},
	{"GOOGLE_TESTING_CLIENT_ID", "google_testing_client_id"},
	{"GOOGLE_TESTING_CLIENT_SECRET", "google_testing_client_secret"},
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gencreds:", err)
		os.Exit(1)
	}
}

func run() error {
	var entries bytes.Buffer
	for _, c := range credentials {
		value := os.Getenv(c.env)
		if value == "" {
			continue
		}
		fmt.Fprintf(&entries, "\t%q: %q,\n", c.key, value)
	}

	if entries.Len() == 0 {
		err := os.Remove(outputPath)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}

	var src bytes.Buffer
	src.WriteString("// Code generated by build/gencreds.go from .env; DO NOT EDIT.\n\n")
	src.WriteString("//go:build mailven_creds\n\npackage oauth2\n\n")
	src.WriteString("// Package-level initialization runs before init(), so these values are\n")
	src.WriteString("// set before config.go decides whether to load the mailven-creds shim.\n")
	src.WriteString("var _ = setCredentials(map[string]string{\n")
	src.Write(entries.Bytes())
	src.WriteString("})\n")

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}
	return writeFile(formatted)
}

// writeFile replaces outputPath atomically and keeps it private to the user.
func writeFile(data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(outputPath), ".credentials_gen-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())

	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), outputPath)
}
