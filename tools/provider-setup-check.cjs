// Guarded Microsoft setup UI check. Start Mailven with the run-mailven skill first.
const assert=require('assert/strict');
const {withFakePage}=require('../.agents/skills/run-mailven/fake-page.js');
const path=require('path');
const fs=require('fs');
const output=process.argv[2];
if (!output) throw Error('Usage: node tools/provider-setup-check.cjs <output-directory>');
fs.mkdirSync(output,{recursive:true});
withFakePage({width:1400,height:1100},async p=>{
 await p.evaluate(()=>{ window.go.app.App.IsOAuthConfigured=async()=>true });
 await p.getByRole('button',{name:'Show sidebar',exact:true}).click();
 await p.waitForTimeout(300);
 await p.screenshot({path:path.join(output,'mail-expanded.png')});
 await p.getByRole('button',{name:'Hide sidebar',exact:true}).click();
 await p.waitForTimeout(300);
 await p.screenshot({path:path.join(output,'mail-collapsed.png')});
 console.log('PASS Mail Accounts expanded and collapsed');
 await p.getByRole('button',{name:'Settings',exact:true}).click();
 await p.getByRole('tab',{name:'Accounts',exact:true}).click();
 await p.getByRole('button',{name:'Add Account',exact:true}).click();
 await p.getByRole('button',{name:'Microsoft / Outlook',exact:true}).click();
 const signIn=p.getByRole('button',{name:'Sign in with Microsoft',exact:true});
 await signIn.waitFor();
 assert(await signIn.isDisabled());
 await p.locator('#email').fill('new@outlook.com');
 await p.locator('#displayName').fill('Test User');
 // The email domain must not select an account type.
 assert.equal(await p.locator('#microsoft-account-type').inputValue(),'');
 await p.locator('#microsoft-account-type').focus();
 await p.keyboard.press('ArrowDown');
 await p.keyboard.press('Enter');
 assert.equal(await p.locator('#microsoft-account-type').inputValue(),'personal');
 assert(!(await signIn.isDisabled()));
 await p.getByRole('button',{name:'Advanced Settings',exact:true}).click();
 assert.equal(await p.locator('#imapHost').inputValue(),'outlook.office365.com');
 assert.equal(await p.locator('#imapPort').inputValue(),'993');
 assert.equal(await p.locator('#smtpHost').inputValue(),'smtp-mail.outlook.com');
 assert.equal(await p.locator('#smtpPort').inputValue(),'587');
 await p.screenshot({path:path.join(output,'personal-setup.png')});
 await p.locator('#microsoft-account-type').selectOption('business');
 assert.equal(await p.locator('#smtpHost').inputValue(),'smtp.office365.com');
 assert.equal(await p.locator('#smtpPort').inputValue(),'587');
 assert.equal(await p.locator('#imapHost').inputValue(),'outlook.office365.com');
 assert.equal(await p.locator('#imapPort').inputValue(),'993');
 await p.locator('#smtpHost').fill('smtp.custom.example');
 await p.locator('#microsoft-account-type').selectOption('personal');
 assert.equal(await p.locator('#smtpHost').inputValue(),'smtp.custom.example');
 console.log('PASS explicit type, keyboard selection, personal/work defaults and custom endpoint preservation');
}).catch(e=>{console.error(e);process.exitCode=1});
