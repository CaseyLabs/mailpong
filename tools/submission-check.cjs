// Guarded submission/recovery checks; run-mailven dev session required.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { withFakePage } = require('../.agents/skills/run-mailven/fake-page.js')
const { launch } = require('../.agents/skills/run-mailven/pw.js')
const out = process.argv[2]
if (!out) throw Error('Usage: node tools/submission-check.cjs <output-directory>')
fs.mkdirSync(out, { recursive: true })
const composerFakes = fs.readFileSync(path.join(__dirname, '../.agents/skills/run-mailven/composer-fakes.js'), 'utf8')
const localEvents = `
const handlers = {};
window.runtime.EventsOnMultiple = (name, cb) => { (handlers[name] ??= []).push(cb); return () => { handlers[name] = handlers[name].filter(x => x !== cb) } };
window.runtime.EventsEmit = (name, ...data) => (handlers[name] ?? []).forEach(cb => cb(...data));
`
const beforeMount = `${localEvents}\n${composerFakes}\nwindow.__installComposerFakes(window);`
const log = p => p.evaluate(() => window.__log.join(' | '))
const review = p => p.getByRole('alertdialog').filter({ hasText: 'Review the previous submission' })
const populate = async p => {
  await p.getByPlaceholder('Subject').fill('Recovery check')
  const to = p.getByPlaceholder(/recipients/i).first()
  await to.fill('sam@example.com'); await to.press('Enter')
  await p.getByRole('region', { name: 'Email composer' }).locator('[contenteditable=true]:visible').first().fill('Recovery body')
}
const risk = 'The server may already have accepted this message. Check Sent before submitting again; duplicates are possible. Draft retained.'

async function main() {
  await withFakePage({ width: 1400, height: 1000 }, async p => {
    await p.getByRole('button', { name: 'Show sidebar', exact: true }).click()
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'mail-expanded.png') })
    await p.getByRole('button', { name: 'Hide sidebar', exact: true }).click()
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'mail-collapsed.png') })
    console.log('PASS Mail Accounts expanded and collapsed')
    await p.evaluate(risk => { window.__sendDelay = 100; window.__submissionReview = { id: 'unknown-restart', outcome: 'unknown', warnings: '' }; window.__sendResult = { outcome: 'unknown', error: risk, draftId: 'draft-1' } }, risk)
    await p.getByRole('button', { name: /Compose/ }).first().click()
    await populate(p)
    const send = p.getByRole('region', { name: 'Email composer' }).getByRole('button', { name: 'Send', exact: true })
    await send.click()
    await review(p).waitFor()
    assert.match(await review(p).innerText(), /duplicates/)
    assert(!/queue |SEND /.test(await log(p)))
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'composer-review.png') })
    await review(p).getByRole('button', { name: 'Cancel', exact: true }).focus()
    await p.keyboard.press('Enter')
    await review(p).waitFor({ state: 'hidden' })
    assert(!/queue |SEND /.test(await log(p)))
    await send.click()
    await review(p).getByRole('button', { name: 'Submit again', exact: true }).focus()
    await p.keyboard.press('Enter')
    await p.getByText(risk, { exact: true }).waitFor()
    assert.match(await log(p), /review token unknown-restart/)
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'composer-unknown.png') })
    console.log('PASS composer restart review, keyboard cancel/confirm, explicit token and unknown guidance')

    // A failed chat reply preserves its draft and requires a separate Retry review.
    await p.evaluate(() => { window.__submissionReview = null })
    await p.locator('.chat-row').first().click()
    const box = p.locator('textarea').last()
    await box.fill('Chat recovery check'); await box.press('Enter')
    await p.getByRole('button', { name: 'Retry', exact: true }).waitFor()
    assert.match(await p.locator('[role=status]').last().innerText(), /duplicates/)
    const before = await log(p)
    await p.evaluate(() => { window.__submissionReview = { id: 'unknown-chat', outcome: 'unknown', warnings: '' } })
    await p.getByRole('button', { name: 'Retry', exact: true }).click()
    await review(p).getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await log(p), before)
    await p.evaluate(() => { window.__sendResult = { outcome: 'accepted', error: '', warnings: 'Draft cleanup fixture failed', draftId: '' } })
    await p.getByRole('button', { name: 'Retry', exact: true }).click()
    await review(p).getByRole('button', { name: 'Submit again', exact: true }).focus()
    await p.keyboard.press('Enter')
    await p.getByText(/Draft cleanup fixture failed/).waitFor()
    assert.match(await p.locator('[role=status]').last().innerText(), /Accepted by server; delivery not confirmed/)
    assert.equal(await p.getByRole('button', { name: 'Retry', exact: true }).count(), 0)
    assert.match(await log(p), /review token unknown-chat/)
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'chat-accepted-warning.png') })
    console.log('PASS chat unknown guidance, explicit reviewed retry and accepted cleanup warning without Retry')
  }, { beforeMount })

  const browser = await launch()
  try {
    const p = await browser.newPage({ viewport: { width: 1000, height: 800 } })
    await p.addInitScript({ path: path.join(__dirname, '../.agents/skills/run-mailven/composer-fakes.js') })
    await p.goto('http://localhost:34115/composer.html')
    await p.getByRole('region', { name: 'Email composer' }).waitFor()
    await p.evaluate(() => { window.__submissionReview = { id: 'unknown-detached', outcome: 'unknown', warnings: '' } })
    await populate(p)
    const send = p.getByRole('region', { name: 'Email composer' }).getByRole('button', { name: 'Send', exact: true })
    await send.click()
    await p.getByRole('button', { name: /Send now/ }).click()
    await review(p).waitFor()
    assert(!/SEND /.test(await log(p)))
    await review(p).getByRole('button', { name: 'Cancel', exact: true }).click()
    await send.click()
    await p.getByRole('button', { name: /Send now/ }).click()
    await review(p).getByRole('button', { name: 'Submit again', exact: true }).focus()
    await p.keyboard.press('Enter')
    await p.waitForFunction(() => window.__log.some(x => x === 'closeWindow'))
    assert.match(await log(p), /review token unknown-detached/)
    await p.waitForTimeout(350)
    await p.screenshot({ path: path.join(out, 'detached-reviewed.png') })
    console.log('PASS detached countdown, review cancel, explicit confirmation and accepted close')
  } finally { await browser.close() }
}
main().catch(err => { console.error(err); process.exitCode = 1 })
